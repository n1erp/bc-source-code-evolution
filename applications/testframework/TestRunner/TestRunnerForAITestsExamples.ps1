# Description: This script demonstrates how to run AI tests using the TestRunnerForAITests module.
<#
1. Import the TestRunnerForAITests module.
2. Initialize the TestRunnerForAITests module.
3. We can set input dataset.
4. We can set the suite definition.
5. We can run the suite and get the test results.
6. We can get the desired test results.
7. We can run individual suite line and get the test results.
#>

# Usage for TestRunnerForAITests.psm1:
Import-Module (Join-Path $PSScriptRoot 'TestRunnerForAITests.psm1') -Force

# Initialize the module
$Credential = $null
$Token = $null
$Environment = 'OnPrem'
$AuthorizationType = 'Windows'
$DisableSSLVerification = $true
$EnvironmentName = $null
$ServiceUrl = $null
$ClientId = $null
$RedirectUri = $null
$AadTenantId = $null
$CompanyId = $null # or [guid]::Empty or '51554dc8-6334-ef11-8e51-6045bdacda57'
$ServerInstance = 'Navision_NAV'
$APIHost = 'http://localhost:7047/'
$ClientSessionTimeout = 60 # in minutes
$TransactionTimeout = 60 # in minutes
$Culture = 'en-US'

TestRunnerForAITests\Initialize-Module -Environment $Environment -AuthorizationType $AuthorizationType -DisableSSLVerification:$DisableSSLVerification -ServerInstance $ServerInstance -CompanyId $CompanyId -ClientSessionTimeout $ClientSessionTimeout -TransactionTimeout $TransactionTimeout -Culture $Culture

# Example of Setting the Input Dataset
TestRunnerForAITests\Set-InputDataset -InputDatasetFilename 'DemoSuiteSampleDataset.jsonl' -InputDatasetPath 'C:\depot\BCApps\src\Tools\AI Test Toolkit\src\SampleTests\DemoSuite\Dataset\DemoSuiteSampleDataset.jsonl'

# Example of Setting the Suite Definition
TestRunnerForAITests\Set-SuiteDefinition -SuiteDefinitionPath 'C:\depot\BCApps\src\Tools\AI Test Toolkit\src\SampleTests\DemoSuite\Demo Suite.xml'

# # Example of running the suite
$SuiteCode = 'Demo Suite'

$TestResults = TestRunnerForAITests\Invoke-AITTests -SuiteCode $SuiteCode -ResetTestSuite

# Write the test results
if ($TestResults.Length -gt 0) {
    Write-Host "Test Run Result:"
    $TestResults = $TestResults | ConvertTo-Json -Depth 5 -AsArray
    Write-Host $TestResults
}
else {
    Write-Host "There are no test results available for the suite code: $SuiteCode."
}

# Example of getting test results with status as error
$TestResults = TestRunnerForAITests\Get-AITSuiteTestResult -SuiteCode $SuiteCode -TestRunVersion 2 -TestStatus 'Error'
Write-Host $TestResults


# Example of running individual suite line
$SuiteCode = 'Demo Suite'

# Get the suite line number from aitTestMethodLines api
$TestMethodLines = Get-AITSuiteTestMethodLines -SuiteCode $SuiteCode | ConvertFrom-Json
$SuiteLineNo = $TestMethodLines[0].lineNumber

$TestResults = TestRunnerForAITests\Invoke-AITTests -SuiteCode $SuiteCode -SuiteLineNo $SuiteLineNo

Write-Host $TestResults
